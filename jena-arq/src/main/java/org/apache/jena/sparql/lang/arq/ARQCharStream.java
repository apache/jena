package org.apache.jena.sparql.lang.arq;

import org.apache.jena.sparql.lang.arq.javacc.CharStream;
import org.apache.jena.sparql.lang.arq.javacc.TokenMgrError;

// Not generated by javacc: the ARQ grammar (main.jj, #ifdef ARQ) uses option
// USER_CHAR_STREAM, and the ARQParser constructors in main.jj create an ARQCharStream.
// Based on SimpleCharStream.java as generated by javacc 7.0.12 from
// https://github.com/javacc/javacc/blob/javacc-7.0.12/src/main/resources/templates/SimpleCharStream.template
// with these changes:
//   Named ARQCharStream, in this package, and "implements CharStream"
//   ExpandBuff doubles the buffer size (GH-1324), as in javacc commit
//     https://github.com/javacc/javacc/commit/3bb3dbff92d29e576441a2ecb6911e7537922900
//     with the correction from bufsize >> 1 to bufsize << 1 in
//     https://github.com/javacc/javacc/pull/317
//     The buffer grows up to MAX_BUFSIZE chars; a longer token is a TokenMgrError.
//     The buffer size must be at least 1.
//   Line and column are not stored for each char in the buffer.
//     They are kept for the start of the current token, and the end of the token is
//     calculated when asked for. After a lexical error, they are right up to the
//     error: the parsers stop there.
//     adjustBeginLineColumn is left out: it is not part of CharStream and is not called.
//   getTrackLineColumn and setTrackLineColumn are public, as required by CharStream
//   FillBuff turns an exception from the Reader into a TokenMgrError, with the exception
//     as its cause, so that only the end of the input is an IOException, and does not
//     read the Reader again after the end of the input. The token manager takes an
//     exception from the char stream as the end of the input. The stream is not meant
//     to be read after a failed read: the parsers stop at the error.

/**
 * The char stream of the ARQ parser: javacc's SimpleCharStream with a buffer that
 * doubles when a token does not fit (GH-1324), without unicode escape processing.
 */

public class ARQCharStream implements CharStream
{
/** Whether parser is static. */
  public static final boolean staticFlag = false;
  int bufsize;
  int available;
  int tokenBegin;
/** Position in buffer. */
  public int bufpos = -1;

  // Line and column of the char at tokenBegin, and the CR/LF state after it.
  protected int column = 0;
  protected int line = 1;

  protected boolean prevCharIsCR = false;
  protected boolean prevCharIsLF = false;

  // False until the first char is read; line and column are then 0, as javacc's SimpleCharStream.
  private boolean tokenStarted = false;

  // Line and column of the char at endBufpos, calculated from those of the char at endTokenBegin.
  private char[] endBuffer = null;
  private int endTokenBegin;
  private int endBufpos;
  private int endLine;
  private int endColumn;
  private boolean endPrevCharIsCR;
  private boolean endPrevCharIsLF;

  protected java.io.Reader inputStream;
  // True once the Reader has returned the end of the input; it is then closed.
  private boolean inputEnded = false;

  protected char[] buffer;
  protected int maxNextCharInd = 0;
  protected int inBuf = 0;
  protected int tabSize = 1;
  protected boolean trackLineColumn = true;

  public void setTabSize(int i) { tabSize = i; }
  public int getTabSize() { return tabSize; }



  // The largest buffer. Some JVMs can't allocate arrays of length close to Integer.MAX_VALUE.
  private static final int MAX_BUFSIZE = Integer.MAX_VALUE - 8;

  protected void ExpandBuff(boolean wrapAround)
  {
    if (bufsize >= MAX_BUFSIZE)
      throw new TokenMgrError("Token too long: the limit is " + MAX_BUFSIZE + " chars", TokenMgrError.LEXICAL_ERROR);
    int newBufsize = (bufsize > MAX_BUFSIZE / 2) ? MAX_BUFSIZE : bufsize << 1;
    char[] newbuffer = new char[newBufsize];

    try
    {
      if (wrapAround)
      {
        System.arraycopy(buffer, tokenBegin, newbuffer, 0, bufsize - tokenBegin);
        System.arraycopy(buffer, 0, newbuffer, bufsize - tokenBegin, bufpos);
        buffer = newbuffer;

        maxNextCharInd = (bufpos += (bufsize - tokenBegin));
      }
      else
      {
        System.arraycopy(buffer, tokenBegin, newbuffer, 0, bufsize - tokenBegin);
        buffer = newbuffer;

        maxNextCharInd = (bufpos -= tokenBegin);
      }
    }
    catch (Throwable t)
    {
      throw new Error(t.getMessage());
    }


    bufsize = newBufsize;
    available = bufsize;
    tokenBegin = 0;
  }

  protected void FillBuff() throws java.io.IOException
  {
    if (maxNextCharInd == available)
    {
      if (available == bufsize)
      {
        if (tokenBegin > 2048)
        {
          bufpos = maxNextCharInd = 0;
          available = tokenBegin;
        }
        else if (tokenBegin < 0)
          bufpos = maxNextCharInd = 0;
        else
          ExpandBuff(false);
      }
      else if (available > tokenBegin)
        available = bufsize;
      else if ((tokenBegin - available) < 2048)
        ExpandBuff(true);
      else
        available = tokenBegin;
    }

    int i = -1;
    if (!inputEnded)
    {
      try {
        i = inputStream.read(buffer, maxNextCharInd, available - maxNextCharInd);
      }
      catch (java.io.IOException | RuntimeException ex)
      {
        // Not the end of the input: the rest of the input would be silently dropped.
        TokenMgrError err = new TokenMgrError("Failed to read the input: " + ex, TokenMgrError.LEXICAL_ERROR);
        err.initCause(ex);
        throw err;
      }
    }
    try {
      if (i == -1)
      {
        if (!inputEnded)
        {
          inputEnded = true;
          inputStream.close();
        }
        throw new java.io.IOException();
      }
      else
        maxNextCharInd += i;
      return;
    }
    catch(java.io.IOException e) {
      --bufpos;
      backup(0);
      if (tokenBegin == -1)
        tokenBegin = bufpos;
      throw e;
    }
  }

/** Start. */
  public char BeginToken() throws java.io.IOException
  {
    // Move line and column on from the start of the previous token to its last char.
    if (tokenStarted)
      lineColumnTo(bufpos);
    endBuffer = null;
    tokenBegin = -1;
    char c = readChar();
    tokenBegin = bufpos;
    UpdateLineColumn(c);
    tokenStarted = true;

    return c;
  }

  protected void UpdateLineColumn(char c)
  {
    column++;

    if (prevCharIsLF)
    {
      prevCharIsLF = false;
      line += (column = 1);
    }
    else if (prevCharIsCR)
    {
      prevCharIsCR = false;
      if (c == '\n')
      {
        prevCharIsLF = true;
      }
      else
        line += (column = 1);
    }

    switch (c)
    {
      case '\r' :
        prevCharIsCR = true;
        break;
      case '\n' :
        prevCharIsLF = true;
        break;
      case '\t' :
        column--;
        column += (tabSize - (column % tabSize));
        break;
      default :
        break;
    }
  }

  // Move line, column and the CR/LF state from the char at tokenBegin to the char at pos.
  private void lineColumnTo(int pos)
  {
    if (endBuffer == buffer && endTokenBegin == tokenBegin && endBufpos == pos)
    {
      line = endLine;
      column = endColumn;
      prevCharIsCR = endPrevCharIsCR;
      prevCharIsLF = endPrevCharIsLF;
      return;
    }
    int i = tokenBegin;
    // Chars from tokenBegin to pos, allowing for the buffer wrapping round.
    // (pos - tokenBegin + bufsize) would overflow int for buffers over 2^30 chars.
    int n = pos - tokenBegin;
    if (n < 0)
      n += bufsize;
    for (; n > 0; n--)
    {
      if (++i == bufsize)
        i = 0;
      UpdateLineColumn(buffer[i]);
    }
  }

  // Calculate the line and column of the char at bufpos.
  private void calcEnd()
  {
    if (endBuffer == buffer && endTokenBegin == tokenBegin && endBufpos == bufpos)
      return;
    int beginLine = line;
    int beginColumn = column;
    boolean beginPrevCharIsCR = prevCharIsCR;
    boolean beginPrevCharIsLF = prevCharIsLF;
    lineColumnTo(bufpos);
    endLine = line;
    endColumn = column;
    endPrevCharIsCR = prevCharIsCR;
    endPrevCharIsLF = prevCharIsLF;
    endBuffer = buffer;
    endTokenBegin = tokenBegin;
    endBufpos = bufpos;
    line = beginLine;
    column = beginColumn;
    prevCharIsCR = beginPrevCharIsCR;
    prevCharIsLF = beginPrevCharIsLF;
  }

/** Read a character. */
  public char readChar() throws java.io.IOException
  {
    if (inBuf > 0)
    {
      --inBuf;

      if (++bufpos == bufsize)
        bufpos = 0;

      return buffer[bufpos];
    }

    if (++bufpos >= maxNextCharInd)
      FillBuff();

    return buffer[bufpos];
  }

  /**
   * @deprecated
   * @see #getEndColumn
   */
  @Deprecated
  public int getColumn() {
    return getEndColumn();
  }

  /**
   * @deprecated
   * @see #getEndLine
   */
  @Deprecated
  public int getLine() {
    return getEndLine();
  }

  /** Get token end column number. */
  public int getEndColumn() {
    if (!tokenStarted)
      return 0;
    calcEnd();
    return endColumn;
  }

  /** Get token end line number. */
  public int getEndLine() {
    if (!tokenStarted)
      return 0;
    calcEnd();
    return endLine;
  }

  /** Get token beginning column number. */
  public int getBeginColumn() {
    return tokenStarted ? column : 0;
  }

  /** Get token beginning line number. */
  public int getBeginLine() {
    return tokenStarted ? line : 0;
  }

/** Backup a number of characters. */
  public void backup(int amount) {

    inBuf += amount;
    if ((bufpos -= amount) < 0)
      bufpos += bufsize;
  }

  // A buffer of no chars never grows: readChar would fail, and the token manager
  // would take that as the end of the input.
  private static void checkBufferSize(int buffersize)
  {
    if (buffersize < 1)
      throw new IllegalArgumentException("Buffer size must be at least 1: " + buffersize);
  }

  /** Constructor. */
  public ARQCharStream(java.io.Reader dstream, int startline,
  int startcolumn, int buffersize)
  {
    checkBufferSize(buffersize);
    inputStream = dstream;
    line = startline;
    column = startcolumn - 1;

    available = bufsize = buffersize;
    buffer = new char[buffersize];
  }

  /** Constructor. */
  public ARQCharStream(java.io.Reader dstream, int startline,
                          int startcolumn)
  {
    this(dstream, startline, startcolumn, 4096);
  }

  /** Constructor. */
  public ARQCharStream(java.io.Reader dstream)
  {
    this(dstream, 1, 1, 4096);
  }

  /** Reinitialise. */
  public void ReInit(java.io.Reader dstream, int startline,
  int startcolumn, int buffersize)
  {
    checkBufferSize(buffersize);
    inputStream = dstream;
    line = startline;
    column = startcolumn - 1;

    if (buffer == null || buffersize != buffer.length)
    {
      available = bufsize = buffersize;
      buffer = new char[buffersize];
    }
    prevCharIsLF = prevCharIsCR = false;
    tokenStarted = false;
    endBuffer = null;
    inputEnded = false;
    tokenBegin = inBuf = maxNextCharInd = 0;
    bufpos = -1;
  }

  /** Reinitialise. */
  public void ReInit(java.io.Reader dstream, int startline,
                     int startcolumn)
  {
    ReInit(dstream, startline, startcolumn, 4096);
  }

  /** Reinitialise. */
  public void ReInit(java.io.Reader dstream)
  {
    ReInit(dstream, 1, 1, 4096);
  }
  /** Constructor. */
  public ARQCharStream(java.io.InputStream dstream, String encoding, int startline,
  int startcolumn, int buffersize) throws java.io.UnsupportedEncodingException
  {
    this(encoding == null ? new java.io.InputStreamReader(dstream) : new java.io.InputStreamReader(dstream, encoding), startline, startcolumn, buffersize);
  }

  /** Constructor. */
  public ARQCharStream(java.io.InputStream dstream, int startline,
  int startcolumn, int buffersize)
  {
    this(new java.io.InputStreamReader(dstream), startline, startcolumn, buffersize);
  }

  /** Constructor. */
  public ARQCharStream(java.io.InputStream dstream, String encoding, int startline,
                          int startcolumn) throws java.io.UnsupportedEncodingException
  {
    this(dstream, encoding, startline, startcolumn, 4096);
  }

  /** Constructor. */
  public ARQCharStream(java.io.InputStream dstream, int startline,
                          int startcolumn)
  {
    this(dstream, startline, startcolumn, 4096);
  }

  /** Constructor. */
  public ARQCharStream(java.io.InputStream dstream, String encoding) throws java.io.UnsupportedEncodingException
  {
    this(dstream, encoding, 1, 1, 4096);
  }

  /** Constructor. */
  public ARQCharStream(java.io.InputStream dstream)
  {
    this(dstream, 1, 1, 4096);
  }

  /** Reinitialise. */
  public void ReInit(java.io.InputStream dstream, String encoding, int startline,
                          int startcolumn, int buffersize) throws java.io.UnsupportedEncodingException
  {
    ReInit(encoding == null ? new java.io.InputStreamReader(dstream) : new java.io.InputStreamReader(dstream, encoding), startline, startcolumn, buffersize);
  }

  /** Reinitialise. */
  public void ReInit(java.io.InputStream dstream, int startline,
                          int startcolumn, int buffersize)
  {
    ReInit(new java.io.InputStreamReader(dstream), startline, startcolumn, buffersize);
  }

  /** Reinitialise. */
  public void ReInit(java.io.InputStream dstream, String encoding) throws java.io.UnsupportedEncodingException
  {
    ReInit(dstream, encoding, 1, 1, 4096);
  }

  /** Reinitialise. */
  public void ReInit(java.io.InputStream dstream)
  {
    ReInit(dstream, 1, 1, 4096);
  }
  /** Reinitialise. */
  public void ReInit(java.io.InputStream dstream, String encoding, int startline,
                     int startcolumn) throws java.io.UnsupportedEncodingException
  {
    ReInit(dstream, encoding, startline, startcolumn, 4096);
  }
  /** Reinitialise. */
  public void ReInit(java.io.InputStream dstream, int startline,
                     int startcolumn)
  {
    ReInit(dstream, startline, startcolumn, 4096);
  }
  /** Get token literal value. */
  public String GetImage()
  {
    if (bufpos >= tokenBegin)
      return new String(buffer, tokenBegin, bufpos - tokenBegin + 1);
    else
      return new String(buffer, tokenBegin, bufsize - tokenBegin) +
                            new String(buffer, 0, bufpos + 1);
  }

  /** Get the suffix. */
  public char[] GetSuffix(int len)
  {
    char[] ret = new char[len];

    if ((bufpos + 1) >= len)
      System.arraycopy(buffer, bufpos - len + 1, ret, 0, len);
    else
    {
      System.arraycopy(buffer, bufsize - (len - bufpos - 1), ret, 0,
                                                        len - bufpos - 1);
      System.arraycopy(buffer, 0, ret, len - bufpos - 1, bufpos + 1);
    }

    return ret;
  }

  /** Reset buffer when finished. */
  public void Done()
  {
    buffer = null;
  }

  public boolean getTrackLineColumn() { return trackLineColumn; }
  public void setTrackLineColumn(boolean tlc) { trackLineColumn = tlc; }
}
